}

/// La aritmética del demo — la única excepción a "toda la aritmética vive en
/// el servidor". El demo va empacado en la app y no tiene Mac atrás, así que
/// editar un movimiento re-agrega aquí el mes y el anual, espejando
/// _summarize_month y _build_dashboard de server.py con sus mismos redondeos
/// (display_cop / display_usd). Solo el demo pasa por aquí; el live sigue
/// pintando lo que el servidor calculó.
enum DemoMath {
    /// normalizeCop del servidor: pesos enteros, mitades hacia arriba.
    private static func displayCop(_ value: Double) -> Double {
        guard value.isFinite, abs(value) >= 0.5 else { return 0 }
        return (value + 0.5).rounded(.down)
    }

    /// normalizeUsd: dos decimales, mitades hacia arriba como JavaScript.
    private static func displayUsd(_ value: Double) -> Double {
        guard value.isFinite, abs(value) >= 0.005 else { return 0 }
        return (value * 100 + 0.5).rounded(.down) / 100
    }

    /// Aplica los cambios (las mismas claves que viajan al buzón del live:
    /// description, category, target_type, amount_cop, paid) y devuelve la
    /// respuesta con el mes tocado y el anual ya re-agregados.
    /// El recibido de un ingreso en el demo. Sí mueve totales: al mes solo le
    /// suman los ingresos recibidos, igual que en _recompute_income_month.
    static func applyingReceived(
        _ received: Bool,
        to income: Income,
        in response: DashboardResponse
    ) -> DashboardResponse {
        editingIncomes(of: income, in: response) { incomes, position in
            incomes[position].received = received
        }
    }

    /// Crear o editar un ingreso en el demo. Con `income` nil es uno nuevo, al
    /// final del mes que se está mirando.
    static func savingIncome(
        _ fields: [String: Outbox.PendingValue],
        to income: Income?,
        monthIndex: Int,
        in response: DashboardResponse
    ) -> DashboardResponse {
        if let income {
            return editingIncomes(of: income, in: response) { incomes, position in
                incomes[position] = applied(fields, to: incomes[position])
            }
        }
        guard let slot = response.months.firstIndex(where: { $0.index == monthIndex }) else {
            return response
        }
        var updated = response
        let blank = Income(
            description: "", amountUsd: 0, usdCop: 0, amountCop: 0, received: false,
            sourcePath: updated.months[slot].incomes.first?.sourcePath,
            // Va al final: es donde lo pone el servidor, y el índice real llega
            // con el próximo snapshot de todos modos.
            sourceIndex: updated.months[slot].incomes.count,
            monthIndex: monthIndex
        )
        updated.months[slot].incomes.append(applied(fields, to: blank))
        recompute(&updated, at: slot)
        return updated
    }

    static func deletingIncome(_ income: Income, in response: DashboardResponse) -> DashboardResponse {
        editingIncomes(of: income, in: response) { incomes, position in
            incomes.remove(at: position)
        }
    }

    /// Encuentra el mes del ingreso, deja que lo toquen y re-agrega.
    private static func editingIncomes(
        of income: Income,
        in response: DashboardResponse,
        _ change: (inout [Income], Int) -> Void
    ) -> DashboardResponse {
        var updated = response
        for slot in updated.months.indices {
            guard let position = updated.months[slot].incomes.firstIndex(where: {
                $0.sourcePath == income.sourcePath && $0.sourceIndex == income.sourceIndex
            }) else { continue }
            change(&updated.months[slot].incomes, position)
            recompute(&updated, at: slot)
            return updated
        }
        return response
    }

    /// Los campos del editor sobre un ingreso. Cuando falta uno de los tres
    /// montos se deriva de los otros dos, como _normalize_new_income_entry.
    private static func applied(
        _ fields: [String: Outbox.PendingValue],
        to income: Income
    ) -> Income {
        func number(_ key: String) -> Double? {
            if case .number(let value)? = fields[key] { return value }
            return nil
        }
        var text = income.description
        if case .text(let value)? = fields["description"] { text = value }
        var received = income.received ?? false
        if case .flag(let value)? = fields["received"] { received = value }

        let usd = number("amount_usd") ?? income.amountUsd ?? 0
        let rate = number("usd_cop") ?? income.usdCop ?? 0
        let cop: Double
        if let given = number("amount_cop") {
            cop = given
        } else if fields["amount_usd"] != nil || fields["usd_cop"] != nil {
            cop = round3(usd * rate)
        } else {
            cop = income.amountCop ?? 0
        }

        return Income(
            id: income.id, description: text, amountUsd: usd, usdCop: rate,
            amountCop: cop, received: received,
            sourcePath: income.sourcePath, sourceIndex: income.sourceIndex,
            monthIndex: income.monthIndex
        )
    }

    /// _recompute_income_month y detrás el resumen del mes y el anual: al mes
    /// solo le suman los ingresos recibidos, y su tasa sale de esos dos totales.
    private static func recompute(_ response: inout DashboardResponse, at slot: Int) {
        let received = response.months[slot].incomes.filter { $0.received ?? false }
        let usd = round3(received.reduce(0) { $0 + ($1.amountUsd ?? 0) })
        let cop = round3(received.reduce(0) { $0 + ($1.amountCop ?? 0) })
        response.months[slot].incomeUsd = usd
        response.months[slot].incomeCop = cop
        response.months[slot].usdCop = usd > 0 ? ((cop / usd) * 100).rounded() / 100 : 0
        summarize(&response.months[slot])
        response.annual = annual(from: response.months, keeping: response.annual)
    }

    private static func round3(_ value: Double) -> Double {
        (value * 1000).rounded() / 1000
    }

    static func applying(
        _ changes: [String: Outbox.PendingValue],
        to entry: Entry,
        in response: DashboardResponse
    ) -> DashboardResponse {
        guard let monthIndex = response.months.firstIndex(where: { month in
            month.entries.contains { sameEntry($0, entry) }
        }) else { return response }
        var updated = response
        var month = updated.months[monthIndex]
        guard let entryIndex = month.entries.firstIndex(where: { sameEntry($0, entry) }) else {
            return response
        }

        var target = month.entries[entryIndex]
        for (field, value) in changes {
            switch (field, value) {
            case ("description", .text(let text)): target.description = text
            case ("category", .text(let text)): target.category = text
            case ("target_type", .text(let text)): target.type = text
            case ("amount_cop", .number(let amount)): target.amountCop = amount
            case ("paid", .flag(let flag)): target.paid = flag
            case ("linked_debts", .list(let ids)): target.linkedDebts = ids
            case ("extra_payment", .flag(let flag)): target.extraPayment = flag
            default: break
            }
        }
        target.amountUsd = month.usdCop > 0 ? displayUsd(target.amountCop / month.usdCop) : 0
        month.entries[entryIndex] = target

        summarize(&month)
        updated.months[monthIndex] = month
        updated.annual = annual(from: updated.months, keeping: updated.annual)
        return updated
    }

    /// Un movimiento nuevo en el demo: nace con id propio, cae al final de
    /// su tipo — o justo después del original cuando es un duplicado — y el
    /// mes y el anual se re-agregan igual que en el servidor.
    static func creating(
        _ fields: [String: Outbox.PendingValue],
        monthIndex: Int,
        after original: Entry?,
        in response: DashboardResponse
    ) -> DashboardResponse {
        guard let position = response.months.firstIndex(where: { $0.index == monthIndex }) else {
            return response
        }
        var updated = response
        var month = updated.months[position]

        var description = ""
        if case .text(let text)? = fields["description"] { description = text }
        var category: String?
        if case .text(let text)? = fields["category"], !text.isEmpty { category = text }
        var type = "needs"
        if case .text(let text)? = fields["type"], !text.isEmpty { type = text }
        var amount = 0.0
        if case .number(let value)? = fields["amount_cop"] { amount = value }
        var paid = false
        if case .flag(let value)? = fields["paid"] { paid = value }
        var linkedDebts: [String]?
        if case .list(let ids)? = fields["linked_debts"], !ids.isEmpty { linkedDebts = ids }
        var extraPayment: Bool?
        if case .flag(let value)? = fields["extra_payment"] { extraPayment = value }

        let nextId = (updated.months.flatMap(\.entries).compactMap(\.entryId).max() ?? 0) + 1
        let entry = Entry(
            description: description,
            category: category,
            amountCop: amount,
            amountUsd: month.usdCop > 0 ? displayUsd(amount / month.usdCop) : 0,
            type: type,
            paid: paid,
            active: nil,
            sourcePath: original?.sourcePath ?? month.entries.first?.sourcePath ?? month.sourcePathByType?[type],
            sourceIndex: month.entries.count,
            entryId: nextId,
            autoGenerated: nil,
            linkedDebts: linkedDebts,
            extraPayment: extraPayment,
            createdAt: nil,
            updatedAt: nil,
            history: []
        )

        if let original, let originalIndex = month.entries.firstIndex(where: { sameEntry($0, original) }) {
            month.entries.insert(entry, at: originalIndex + 1)
        } else if let lastOfType = month.entries.lastIndex(where: { ($0.type ?? "needs") == type }) {
            month.entries.insert(entry, at: lastOfType + 1)
        } else {
            month.entries.append(entry)
        }

        summarize(&month)
        updated.months[position] = month
        updated.annual = annual(from: updated.months, keeping: updated.annual)
        return updated
    }

    /// Borrar en el demo: fuera el movimiento, y a re-agregar mes y anual.
    static func deleting(_ entry: Entry, in response: DashboardResponse) -> DashboardResponse {
        guard let position = response.months.firstIndex(where: { month in
            month.entries.contains { sameEntry($0, entry) }
        }) else { return response }
        var updated = response
        var month = updated.months[position]
        month.entries.removeAll { sameEntry($0, entry) }
        summarize(&month)
        updated.months[position] = month
        updated.annual = annual(from: updated.months, keeping: updated.annual)
        return updated
    }

    /// La identidad del movimiento: el id permanente, o ruta|índice.
    private static func sameEntry(_ a: Entry, _ b: Entry) -> Bool {
        if let left = a.entryId, let right = b.entryId { return left == right }
        return a.sourcePath != nil && a.sourcePath == b.sourcePath && a.sourceIndex == b.sourceIndex
    }

    /// _summarize_month: totales, tipos, categorías, la tabla de resumen y el
    /// "Free" que se enseña como deseos cuando el mes queda en verde.
    private static func summarize(_ month: inout MonthSummary) {
        var byType: [String: Double] = ["debts": 0, "needs": 0, "savings": 0, "wants": 0]
        var byCategory: [String: Double] = [:]
        var total = 0.0
        var paid = 0.0

        for entry in month.entries {
            let value = displayCop(entry.amountCop)
            total += value
            if entry.isPaid { paid += value }
            var type = (entry.type ?? "").trimmingCharacters(in: .whitespaces).lowercased()
            if byType[type] == nil { type = "needs" }
            byType[type, default: 0] += value
            let category = (entry.category ?? "").trimmingCharacters(in: .whitespaces)
            byCategory[category.isEmpty ? "—" : category, default: 0] += value
        }

        month.totalOutcomes = displayCop(total)
        month.paidOutcomes = displayCop(paid)
        byType = byType.mapValues(displayCop)
        byCategory = byCategory.mapValues(displayCop)
        month.free = displayCop(month.incomeCop - month.totalOutcomes)
        month.afterPaid = displayCop(month.incomeCop - month.paidOutcomes)

        var displayTypes = byType
        if month.free > 0 {
            displayTypes["wants", default: 0] += month.free
            byCategory["Free", default: 0] += month.free
        }
        month.byType = byType
        month.displayTypes = displayTypes
        month.byCategory = byCategory
            .map { CategoryTotal(category: $0.key, total: $0.value) }
            .sorted { $0.total > $1.total }

        let usdCop = month.usdCop
        let incomeCop = month.incomeCop
        func row(_ label: String, _ value: Double) -> SummaryRow {
            SummaryRow(
                label: label,
                cop: value,
                usd: usdCop > 0 ? displayUsd(value / usdCop) : 0,
                ratio: incomeCop > 0 ? value / incomeCop * 100 : 0
            )
        }
        var rows = [SummaryRow(label: "incomes", cop: incomeCop, usd: month.incomeUsd, ratio: 100)]
        for key in ["savings", "needs", "wants", "debts"] {
            rows.append(row(key, displayTypes[key] ?? 0))
        }
        rows.append(row("after_paid", month.afterPaid ?? 0))
        if month.free < 0 {
            rows.append(row("deficit", abs(month.free)))
        }
        month.summaryRows = rows
    }

    /// La parte anual de _build_dashboard: sumas de los meses, y en dólares
    /// cada mes convierte con su propia tasa antes de sumar.
    private static func annual(from months: [MonthSummary], keeping previous: AnnualSummary?) -> AnnualSummary? {
        guard let previous else { return nil }
        var byType: [String: Double] = ["debts": 0, "needs": 0, "savings": 0, "wants": 0]
        var displayTypes = byType
        var byCategory: [String: Double] = [:]
        for month in months {
            for (key, value) in month.byType { byType[key, default: 0] += value }
            for (key, value) in month.displayTypes { displayTypes[key, default: 0] += value }
            for item in month.byCategory { byCategory[item.category, default: 0] += item.total }
        }

        func metric(_ pick: (MonthSummary) -> Double) -> Money {
            Money(
                cop: displayCop(months.reduce(0) { $0 + pick($1) }),
                usd: displayUsd(
                    months.filter { $0.usdCop > 0 }.reduce(0) { $0 + pick($1) / $1.usdCop }
                )
            )
        }

        var annual = previous
        annual.totalOutcomes = displayCop(months.reduce(0) { $0 + $1.totalOutcomes })
        annual.free = displayCop(months.reduce(0) { $0 + $1.free })
        annual.averageFree = displayCop(annual.free / Double(max(months.count, 1)))
        annual.byType = byType.mapValues(displayCop)
        annual.displayTypes = displayTypes.mapValues(displayCop)
        annual.byCategory = byCategory
            .map { CategoryTotal(category: $0.key, total: displayCop($0.value)) }
            .sorted { $0.total > $1.total }
        annual.totals = [
            "income": metric { $0.incomeCop },
            "outcomes": metric { $0.totalOutcomes },
            "free": metric { $0.free },
            "needs": metric { $0.byType["needs"] ?? 0 },
            "wants": metric { $0.displayTypes["wants"] ?? 0 },
            "savings": metric { $0.byType["savings"] ?? 0 },
            "debts": metric { $0.byType["debts"] ?? 0 },
        ]
        return annual
    }
