import Foundation

/// Lo que contesta GET /api/dashboard: un año ya agregado por server.py.
/// La app no suma nada por su cuenta — la misma regla que el cliente web:
/// toda la aritmética vive en el servidor y los clientes solo pintan.
struct DashboardResponse: Decodable {
    let ok: Bool
    let years: [String]
    let year: String
    /// var: el demo edita en memoria y DemoMath re-agrega estas piezas.
    var months: [MonthSummary]
    var annual: AnnualSummary?
}

/// mobile/dashboard.json: todos los años ya calculados por el servidor y
/// sincronizados por iCloud. Cada entrada es la misma respuesta de
/// /api/dashboard, así que el resto de la app no distingue la fuente.
struct MobileSnapshot: Decodable {
    let generatedAt: String?
    let years: [String]
    let dashboards: [String: DashboardResponse]
    /// El dataset de muestra: enseñar la app sin enseñar las finanzas.
    let demo: SnapshotDataset?
    /// El catálogo compartido de categorías, para el selector del modal de
    /// edición. Opcional: un snapshot viejo simplemente no lo trae.
    let categories: [String]?
    /// Las deudas activas del dataset, para el selector de abonos.
    let debts: [DebtOption]?
    /// El módulo de deudas del demo, ya calculado.
    let debtsDetail: [DebtDetail]?
    /// El plan alimentario del demo, ya resuelto.
    let nutrition: NutritionSnapshot?
}

struct SnapshotDataset: Decodable {
    let years: [String]
    let dashboards: [String: DashboardResponse]
}

/// mobile/manifest.json: el índice del snapshot partido por año — qué años
