struct Entry: Decodable, Identifiable {
    var id = UUID()
    var description: String?
    var category: String?
    var amountCop: Double
    var amountUsd: Double?
    var type: String?
    var paid: Bool?
    /// La bandera vieja de pagado, presente en archivos anteriores.
    let active: Bool?
    /// De dónde salió el movimiento — lo que el buzón necesita para pedirle
    /// al servidor del Mac que lo cambie.
    let sourcePath: String?
    let sourceIndex: Int?
    /// El id permanente y numérico que el servidor le asigna: encuentra el
    /// movimiento aunque la lista se reordene.
    let entryId: Int?
    /// true en las cuotas que nacen de una deuda: de esas solo se puede
    /// tocar el pagado — la edición vive en la deuda.
    let autoGenerated: Bool?
    /// A qué deudas abona este movimiento, y la marca de abono extra — lo
    /// que la web pone cuando el tipo es deudas y se eligen deudas.
    var linkedDebts: [String]?
    var extraPayment: Bool?
    /// El rastro que el servidor guarda con cada edición, más los sellos de
    /// vida del movimiento. Opcionales: archivos viejos no los traen.
    let createdAt: String?
    let updatedAt: String?
    let history: [HistoryEvent]?

    var isPaid: Bool { paid ?? active ?? false }

    private enum CodingKeys: String, CodingKey {
        case description, category, amountCop, amountUsd, type, paid, active
        case sourcePath, sourceIndex, autoGenerated
        case linkedDebts, extraPayment
        case createdAt, updatedAt, history
        case entryId = "id"
    }
}

/// Una deuda activa, en lo mínimo que el selector de abonos necesita. Viaja
/// en el manifiesto (y dentro del demo empacado).
struct DebtOption: Decodable, Identifiable {
    let id: String
    let name: String
    /// Lo que le queda por pagar, cuando se sabe. El manifiesto solo trae id y
    /// nombre; el detalle de deudas sí lo sabe, y de ahí se arma la lista que
    /// ve el editor — que necesita el saldo para no dejar abonar de más.
    var remainingBalance: Double?

    init(id: String, name: String, remainingBalance: Double? = nil) {
        self.id = id
        self.name = name
        self.remainingBalance = remainingBalance
    }
}

/// mobile/nutrition.json: el plan alimentario con la semana ya resuelta y la
/// lista de compras ya sumada. Como en deudas, el teléfono no calcula nada:
/// solo pinta lo que el servidor dejó escrito.
struct NutritionSnapshot: Decodable {
    let generatedAt: String?
    /// A qué archivo apuntan el dado y las exclusiones.
    var planPath = ""
    var ingredients: [PlanIngredient] = []
    var week: [PlanDay] = []
    var catalog: [String: [PlannedMeal]] = [:]
    /// Pares [título, texto], tal como los guarda el plan.
    var groundRules: [[String]] = []
    var condimentsYes = ""
    var condimentsNo = ""
    var excludedIngredients: [String] = []
    var shopping: ShoppingList?

    private enum CodingKeys: String, CodingKey {
        case generatedAt, planPath, ingredients, week, catalog, groundRules
        case condimentsYes, condimentsNo, excludedIngredients, shopping
    }

    /// A mano y no sintetizado: Decodable exige la clave aunque la propiedad
    /// tenga valor por defecto, y un dataset sin plan alimentario manda un
    /// objeto vacío. Sin esto, no tener plan sería un error de decodificación
    /// en vez de una sección vacía.
    init(from decoder: Decoder) throws {
        let box = try decoder.container(keyedBy: CodingKeys.self)
        generatedAt = try box.decodeIfPresent(String.self, forKey: .generatedAt)
        planPath = try box.decodeIfPresent(String.self, forKey: .planPath) ?? ""
        ingredients = try box.decodeIfPresent([PlanIngredient].self, forKey: .ingredients) ?? []
        week = try box.decodeIfPresent([PlanDay].self, forKey: .week) ?? []
        catalog = try box.decodeIfPresent([String: [PlannedMeal]].self, forKey: .catalog) ?? [:]
        groundRules = try box.decodeIfPresent([[String]].self, forKey: .groundRules) ?? []
        condimentsYes = try box.decodeIfPresent(String.self, forKey: .condimentsYes) ?? ""
        condimentsNo = try box.decodeIfPresent(String.self, forKey: .condimentsNo) ?? ""
        excludedIngredients = try box.decodeIfPresent([String].self, forKey: .excludedIngredients) ?? []
        shopping = try box.decodeIfPresent(ShoppingList.self, forKey: .shopping)
    }

    /// Sin plan que mostrar.
    var isEmpty: Bool { week.isEmpty && groundRules.isEmpty && (shopping?.lines.isEmpty ?? true) }

    /// Las comidas de un tipo, en el orden del catálogo.
    func catalog(for slot: MealSlot) -> [PlannedMeal] {
        catalog[slot.rawValue] ?? []
    }
}

/// Los cuatro momentos del día, en el orden en que se comen.
enum MealSlot: String, CaseIterable, Identifiable {
    case breakfast, lunch, snack, dinner

    var id: String { rawValue }

    var label: String {
        switch self {
        case .breakfast: return "Desayuno"
        case .lunch: return "Almuerzo"
        case .snack: return "Snack"
        case .dinner: return "Cena"
        }
    }

    var plural: String {
        switch self {
        case .breakfast: return "Desayunos"
        case .lunch: return "Almuerzos"
        case .snack: return "Snacks"
        case .dinner: return "Cenas"
        }
    }

    var icon: String {
        switch self {
        case .breakfast: return "sun.horizon"
        case .lunch: return "fork.knife"
        case .snack: return "leaf"
        case .dinner: return "moon"
        }
    }
}

