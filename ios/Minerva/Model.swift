/// Una edición del histórico: cuándo, desde dónde, y qué campos cambiaron.
struct HistoryEvent: Decodable, Identifiable {
    var id = UUID()
    let changedAt: String?
    let changedBy: String?
    let changes: [String: FieldChange]?

    private enum CodingKeys: String, CodingKey {
        case changedAt, changedBy, changes
    }

    struct FieldChange: Decodable {
        let from: LooseValue?
        let to: LooseValue?
    }
}

/// Un valor del histórico tal como venga: texto, número o bandera.
enum LooseValue: Decodable {
    case text(String)
    case number(Double)
    case flag(Bool)

    init(from decoder: Decoder) throws {
        let container = try decoder.singleValueContainer()
        if let flag = try? container.decode(Bool.self) {
            self = .flag(flag)
        } else if let number = try? container.decode(Double.self) {
            self = .number(number)
        } else {
            self = .text(try container.decode(String.self))
        }
    }

    /// Cómo se enseña en la hoja de histórico.
    var display: String {
        switch self {
        case .text(let value): return value.isEmpty ? "—" : value
        case .number(let value): return Format.copPlain(value)
        case .flag(let value): return value ? "Sí" : "No"
        }
    }
}

struct Income: Decodable, Identifiable {
