const DICTIONARIES: Record<Language, Dictionary> = { es, en };

export function normalizeLanguage(value: unknown): Language {
  const language = String(value ?? "").trim().toLowerCase();
  return (LANGUAGES as readonly string[]).includes(language) ? (language as Language) : DEFAULT_LANGUAGE;
}

/** Same interpolation as the original: {token} is replaced from params. */
export function translate(
  language: Language,
  key: string,
  params: Record<string, string | number> = {},
): string {
  const entry = DICTIONARIES[language][key] ?? DICTIONARIES[DEFAULT_LANGUAGE][key] ?? key;
  return entry.replace(/\{(\w+)\}/g, (match, token: string) =>
    Object.prototype.hasOwnProperty.call(params, token) ? String(params[token]) : match,
  );
}
